"""Run the simulation validation benchmarks with the real Gmsh + CalculiX pipeline and print a Markdown report.

    python scripts/sim_benchmarks.py > ../../docs/validation/benchmark-results.md

Cases (all closed-form references are textbook results; see docs/validation/simulation-benchmarks.md):
  S1 cantilever 200x20x20 mm, E=210 GPa, nu=0.3, tip shear 1 kN  -> Timoshenko tip deflection
  S2 same cantilever, bending stress on the top surface at mid-span -> M*c/I = 75 MPa
  S3 same bar, axial 10 kN                                          -> F*L/(E*A)
  T1 bar 100x10x10 mm, k=50 W/mK, T=20 degC at x=0, q=0.01 W/mm^2 in at x=L -> T(L) = 20 + q*L/k = 40 degC
  T2 same bar, T=100 degC at x=0, convection h=0.001 W/mm^2K to 20 degC at x=L -> T(L) = 46.667 degC
"""

from __future__ import annotations

import os
import shutil
import sys
import tempfile
import time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from autoforge.kernel import schema as S  # noqa: E402
from autoforge.kernel.builder import DocBuilder  # noqa: E402
from autoforge.sim import calculix as C  # noqa: E402
from autoforge.sim.pipeline import run  # noqa: E402

E, NU = 210000.0, 0.3


def bar(dims):
    b = DocBuilder()
    fid = b.feature(S.PrimitiveF, shape="box", size=dims, body="Beam")
    return b.build().model_dump(mode="json"), fid


def static(fid, load, size, conv=False):
    return {"analysis": "static", "body": "Beam", "mesh": {"size_mm": size}, "convergence_study": conv,
            "material": {"name": "benchmark steel", "youngs_modulus_mpa": E, "poisson_ratio": NU, "source": "benchmark"},
            "supports": [{"faces": [f"{fid}:-x"]}], "loads": [{"type": "force", "faces": [f"{fid}:+x"], "vector_n": load}]}


def solve(content, setup):
    wd = tempfile.mkdtemp(prefix="afbench-")
    try:
        t = time.time()
        r = run(content, setup, wd)
        r["wall_s"] = time.time() - t
        return r
    finally:
        shutil.rmtree(wd, ignore_errors=True)


def main() -> None:
    rows = []
    content, fid = bar((200, 20, 20))
    L, A, I, G = 200.0, 400.0, 20**4 / 12, E / (2 * (1 + NU))
    kappa = 10 * (1 + NU) / (12 + 11 * NU)  # Cowper shear coefficient, rectangle
    for size in (5.0, 3.0):
        r = solve(content, static(fid, (0, 0, -1000), size))
        exact = 1000 * L**3 / (3 * E * I) + 1000 * L / (kappa * G * A)
        rows.append(("S1", f"Cantilever tip deflection, h={size:g} mm", exact, r["summary"]["max_displacement_mm"], "mm", r))
        P = np.array(r["viz"]["positions"], float).reshape(-1, 3)
        vm = np.array(r["viz"]["von_mises"], float)
        sel = (np.abs(P[:, 0] - 100) < size * 0.6) & (np.abs(P[:, 2] - 20) < 1e-6) & (np.abs(P[:, 1] - 10) < 6)
        rows.append(("S2", f"Top-surface bending stress at mid-span, h={size:g} mm", 1000 * 100 * 10 / I, float(vm[sel].mean()), "MPa", r))
    r = solve(content, static(fid, (10000, 0, 0), 5.0))
    rows.append(("S3", "Axial extension, h=5 mm", 10000 * L / (E * A), r["summary"]["max_displacement_mm"], "mm", r))
    tcontent, tfid = bar((100, 10, 10))
    th = {"analysis": "thermal", "body": "Beam", "mesh": {"size_mm": 4}, "material": {"name": "k50", "thermal_conductivity_w_mk": 50},
          "temperatures": [{"type": "temperature", "faces": [f"{tfid}:-x"], "value_c": 20}],
          "fluxes": [{"type": "heat_flux", "faces": [f"{tfid}:+x"], "value_w_mm2": 0.01}]}
    r = solve(tcontent, th)
    rows.append(("T1", "Conduction with end heat flux", 20 + 0.01 * 100 / 0.05, r["summary"]["max_temperature_c"], "°C", r))
    th = {"analysis": "thermal", "body": "Beam", "mesh": {"size_mm": 4}, "material": {"name": "k50", "thermal_conductivity_w_mk": 50},
          "temperatures": [{"type": "temperature", "faces": [f"{tfid}:-x"], "value_c": 100}],
          "convection": [{"type": "convection", "faces": [f"{tfid}:+x"], "h_w_mm2k": 0.001, "ambient_c": 20}]}
    r = solve(tcontent, th)
    rows.append(("T2", "Conduction with convective end", 20 + (80 / 3000) / 0.001, r["summary"]["min_temperature_c"], "°C", r))

    print("# Simulation benchmark results")
    print()
    print(f"_Generated by `services/api/scripts/sim_benchmarks.py` with {C.ccx_version('ccx')} and the production pipeline "
          "(Gmsh C3D10 mesh -> CalculiX -> AutoForge post-processing)._")
    print()
    print("| Case | Quantity | Reference | AutoForge | Error | Elements | Nodes | Equilibrium imbalance | Wall time |")
    print("|---|---|---|---|---|---|---|---|---|")
    for case, name, ref, val, unit, r in rows:
        eq = (r["summary"].get("equilibrium") or {}).get("relative_imbalance")
        print(f"| {case} | {name} | {ref:.6g} {unit} | {val:.6g} {unit} | {100 * (val - ref) / ref:+.2f}% | {r['mesh']['elements']} | "
              f"{r['mesh']['nodes']} | {'—' if eq is None else f'{eq:.1e}'} | {r['wall_s']:.1f} s |")


if __name__ == "__main__":
    main()
