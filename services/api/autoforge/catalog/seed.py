def seed_reference_data(db: Session) -> dict[str, int]:
    counts = {"materials": 0, "licenses": 0, "items": 0}
    for key, name, cat, std, rho, E, nu, sy, su, k, cp, a in MATERIALS:
        if db.scalar(select(M.Material.id).where(M.Material.key == key)):
            continue
        db.add(M.Material(key=key, name=name, category=cat, standard=std, density_kg_m3=rho, youngs_modulus_mpa=E, poisson_ratio=nu,
                          yield_strength_mpa=sy, ultimate_strength_mpa=su, thermal_conductivity_w_mk=k, specific_heat_j_kgk=cp,
                          thermal_expansion_1_k=a, value_basis="typical", source=TYPICAL_SRC,
                          verification_status="typical_reference"))
        counts["materials"] += 1
    lic_ids = {}
    for key, name, spdx, url, redist, attrib, commercial, notes in LICENSES:
        row = db.scalar(select(M.AssetLicense).where(M.AssetLicense.key == key))
        if row is None:
            row = M.AssetLicense(key=key, name=name, spdx_id=spdx, url=url, redistribution_allowed=redist,
                                 attribution_required=attrib, commercial_use_allowed=commercial, notes=notes)
            db.add(row)
            db.flush()
            counts["licenses"] += 1
        lic_ids[key] = row.id
    for r in catalog_records():
        if db.scalar(select(M.ComponentCatalogItem.id).where(M.ComponentCatalogItem.name == r["name"],
                                                             M.ComponentCatalogItem.org_id.is_(None))):
            continue
        db.add(M.ComponentCatalogItem(
            name=r["name"], category=r["category"], subcategory=r["subcategory"], domain=r["domain"], asset_class="generated",
            manufacturer=None, part_number=r["part_number"], standard=r["standard"], description=r["description"],
            specs=r["specs"], material=None, mass_kg=None, image_key=None,
            image_attribution="Rendered from AutoForge-generated geometry (no product photograph)",
            cad_content=r["cad"].model_dump(mode="json"), cad_format="autoforge-parametric", spec_source=r["spec_source"],
            source_url=r["source_url"], source_retrieved_at=r["retrieved"], license_id=lic_ids["af-generated"], units="mm",
            measurement_basis="Nominal/maximum dimensions as stated per field", compatibility_notes=r["compat"], revision="1",
            completeness=completeness(r["category"], r["specs"]),
            verification_status="standard_derived" if r["standard"] and "format" not in r["standard"] else "nominal_designation",
            safety_critical=r["safety_critical"], tags=r["tags"]))
        counts["items"] += 1
    return counts
