"""Reference data seeding (idempotent).

Data policy
-----------
* Materials: generic *typical* handbook values, labelled ``typical_reference``.
  They are not certified values for any specific heat or supplier.
* Catalog items in the seed are ``generated`` asset-class records whose
  dimensions come from published standards (ISO 15 boundary dimensions,
  ISO 4762 / ISO 4032 / ISO 7089 key dimensions) or from the cell-format
  designation (18650/21700/4680 nominal size). Geometry is a simplified
  envelope generated by AutoForge; internal features (raceways, threads) are
  not modelled.
* Manufacturer-specific values (load ratings, mass, capacity, price) are left
  empty and reported as *missing*. No manufacturer data is fabricated.
"""

